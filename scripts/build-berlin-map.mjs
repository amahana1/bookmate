// One-off generator for src/lib/berlin-map.ts.
// Input: the Berlin district boundaries GeoJSON in EPSG:25833 (metres), from the Geoportal Berlin WFS:
//   https://gdi.berlin.de/services/wfs/alkis_bezirke?service=WFS&version=2.0.0&request=GetFeature
//     &typeNames=alkis_bezirke:bezirksgrenzen&outputFormat=application/json&srsName=EPSG:25833
// Licence: Datenlizenz Deutschland – Zero – Version 2.0 (no attribution required).
// Usage: node scripts/build-berlin-map.mjs <bezirke.json> src/lib/berlin-map.ts
import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, output] = process.argv;
if (!input || !output) throw new Error('usage: node scripts/build-berlin-map.mjs <bezirke.json> <out.ts>');

const WIDTH = 1000;
const TOLERANCE_M = 40; // Douglas–Peucker tolerance in metres (about 1 map unit)
const MIN_AREA_M2 = 200_000; // drop islands smaller than 0.2 km²
// Labels that would collide in the crowded centre search only part of their district (map units, y grows south).
// Neukölln's best spot sits right under Tempelhof-Schöneberg's label, so it uses its southern half (Britz–Rudow).
const LABEL_MIN_Y = { 'Neukölln': 600 };

const geo = JSON.parse(readFileSync(input, 'utf8'));
const polysOf = (g) => (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]);

function ringArea(r) {
  let a = 0;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]);
  return Math.abs(a / 2);
}

function segDist2(p, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const len = dx * dx + dy * dy;
  let t = len ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len : 0;
  t = Math.max(0, Math.min(1, t));
  const x = a[0] + t * dx - p[0], y = a[1] + t * dy - p[1];
  return x * x + y * y;
}

function simplify(ring, tol) {
  const keep = new Uint8Array(ring.length);
  keep[0] = keep[ring.length - 1] = 1;
  const stack = [[0, ring.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    let max = 0, idx = -1;
    for (let i = s + 1; i < e; i++) {
      const d = segDist2(ring[i], ring[s], ring[e]);
      if (d > max) { max = d; idx = i; }
    }
    if (idx !== -1 && max > tol * tol) { keep[idx] = 1; stack.push([s, idx], [idx, e]); }
  }
  return ring.filter((_, i) => keep[i]);
}

// Bounds over all districts.
let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
for (const f of geo.features) for (const poly of polysOf(f.geometry)) for (const [x, y] of poly[0]) {
  minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
}
const scale = WIDTH / (maxX - minX);
const HEIGHT = Math.ceil((maxY - minY) * scale);
const project = ([x, y]) => [Math.round((x - minX) * scale * 10) / 10, Math.round((maxY - y) * scale * 10) / 10];

function inside(p, rings) {
  let c = false;
  for (const r of rings) for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    if ((r[i][1] > p[1]) !== (r[j][1] > p[1]) && p[0] < ((r[j][0] - r[i][0]) * (p[1] - r[i][1])) / (r[j][1] - r[i][1]) + r[i][0]) c = !c;
  }
  return c;
}

/** Point inside the polygon farthest from its edges (brute-force pole of inaccessibility, in map units). */
function labelPoint(rings, minY = -Infinity) {
  const xs = rings[0].map((p) => p[0]), ys = rings[0].map((p) => p[1]);
  const [x0, x1, y1] = [Math.min(...xs), Math.max(...xs), Math.max(...ys)];
  const y0 = Math.max(Math.min(...ys), minY);
  let best = { x: (x0 + x1) / 2, y: (y0 + y1) / 2, r: 0 };
  for (let x = x0; x <= x1; x += 2) for (let y = y0; y <= y1; y += 2) {
    if (!inside([x, y], rings)) continue;
    let d = Infinity;
    for (const r of rings) for (let i = 0, j = r.length - 1; i < r.length; j = i++) d = Math.min(d, segDist2([x, y], r[j], r[i]));
    d = Math.sqrt(d);
    if (d > best.r) best = { x, y, r: d };
  }
  return { x: Math.round(best.x), y: Math.round(best.y), r: Math.round(best.r) };
}

const out = {};
for (const f of geo.features) {
  const name = f.properties.namgem;
  const polys = polysOf(f.geometry)
    .filter((poly) => ringArea(poly[0]) >= MIN_AREA_M2)
    .map((poly) => poly.map((ring) => simplify(ring, TOLERANCE_M).map(project)));
  polys.sort((a, b) => ringArea(b[0]) - ringArea(a[0]));
  const d = polys.map((poly) => poly.map((ring) => `M${ring.slice(0, -1).map((p) => p.join(' ')).join(' ')}Z`).join('')).join('');
  out[name] = { d, ...labelPoint(polys[0], LABEL_MIN_Y[name]) };
}

const names = Object.keys(out).sort((a, b) => a.localeCompare(b, 'de'));
const body = names.map((n) => `  ${JSON.stringify(n)}: { x: ${out[n].x}, y: ${out[n].y}, r: ${out[n].r}, d: ${JSON.stringify(out[n].d)} },`).join('\n');
writeFileSync(output, `// Generated by scripts/build-berlin-map.mjs from Geoportal Berlin, ALKIS Bezirke
// (Datenlizenz Deutschland – Zero – Version 2.0). Do not edit by hand.

export const BERLIN_MAP_WIDTH = ${WIDTH};
export const BERLIN_MAP_HEIGHT = ${HEIGHT};

/** Each Bezirk: SVG path in map units, plus the label point (x, y) farthest from its edges and that distance r. */
export const DISTRICT_SHAPES: Record<string, { x: number; y: number; r: number; d: string }> = {
${body}
};
`);
console.log(`wrote ${output}: ${WIDTH}x${HEIGHT}, ${names.length} districts, ${(body.length / 1024).toFixed(1)} KB`);
for (const n of names) console.log(`${n}: label ${out[n].x},${out[n].y} r=${out[n].r}`);
